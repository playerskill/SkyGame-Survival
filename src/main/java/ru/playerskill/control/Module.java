package ru.playerskill.control;

/**
 * Отдельная функция плагина. Создаётся диспетчером, живёт и убирается целиком.
 */
public interface Module {

    /** Название модуля для логов и сообщений. */
    String getName();

    /** Регистрация слушателей и запуск задач. */
    void enable();

    /** Снятие слушателей и отмена задач — модуль убирает за собой сам. */
    void disable();
}
